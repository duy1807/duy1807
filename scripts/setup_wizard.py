#!/usr/bin/env python3
"""Interactive VPS configuration (run as root after deploy/install.sh):

    sudo /opt/solbot/.venv/bin/python /opt/solbot/scripts/setup_wizard.py

Asks for the RPC key, gRPC token, Telegram bot token (detects your Telegram user id), creates or imports the
wallet as an encrypted keystore, stores the passphrase as an encrypted systemd credential, writes .env
(chmod 600, ALLOW_LIVE=false), runs `doctor` and optionally starts the service.
Secrets are typed hidden and never printed. Nothing is ever sent to the chain.
"""
from __future__ import annotations

import argparse
import getpass
import json
import os
import pwd
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PUBLICNODE_RPC = "https://solana-rpc.publicnode.com"
PUBLICNODE_GRPC = "solana-yellowstone-grpc.publicnode.com:443"
JITO_TOKYO = "https://tokyo.mainnet.block-engine.jito.wtf"


# ----------------------------------------------------------------------------------- helpers --
def ask(prompt: str, default: str | None = None, secret: bool = False) -> str:
    suffix = f" [{default}]" if default and not secret else (" [Enter = giữ nguyên]" if default else "")
    while True:
        v = (getpass.getpass(f"{prompt}{suffix}: ") if secret else input(f"{prompt}{suffix}: ")).strip()
        if v:
            return v
        if default is not None:
            return default
        print("  (bắt buộc)")


def yes(prompt: str, default: bool = True) -> bool:
    v = input(f"{prompt} [{'Y/n' if default else 'y/N'}]: ").strip().lower()
    return default if not v else v in ("y", "yes", "c", "có", "co")


def mask(s: str) -> str:
    return (s[:4] + "…" + s[-3:]) if len(s) > 10 else "***"


def rpc_url_from(inp: str) -> str:
    """Accept a full RPC URL or a bare Helius API key."""
    inp = inp.strip()
    if inp.startswith("http://") or inp.startswith("https://"):
        return inp
    if re.fullmatch(r"[0-9a-fA-F-]{20,}", inp):
        return f"https://mainnet.helius-rpc.com/?api-key={inp}"
    raise ValueError("không phải URL RPC hay API key Helius hợp lệ")


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip()
    return out


_PLACEHOLDERS = ("example", "your-", "123456789")


def real_values(env: dict[str, str]) -> dict[str, str]:
    """Drop empty and template placeholder values (.env.example) so they are never offered as defaults."""
    return {k: v for k, v in env.items() if v and not any(p in v for p in _PLACEHOLDERS)}


def render_env(v: dict[str, str]) -> str:
    primary, backup = v["PRIMARY_RPC"], v.get("BACKUP_RPC", PUBLICNODE_RPC)
    rpcs = ",".join(dict.fromkeys([primary, backup]))
    lines = [
        "# Generated by scripts/setup_wizard.py — chmod 600, never commit",
        "DB_PATH=data/solbot.sqlite3",
        f"WALLET_ENCRYPTED_PATH={v['WALLET_ENCRYPTED_PATH']}",
        "",
        f"TELEGRAM_BOT_TOKEN={v['TELEGRAM_BOT_TOKEN']}",
        f"TELEGRAM_ALLOWED_USER_IDS={v['TELEGRAM_ALLOWED_USER_IDS']}",
        "",
        f"RPC_URLS={rpcs}",
        f"SIM_RPC_URL={rpcs}",
        f"BUNDLE_SIM_RPC_URL={primary}",
        f"VERIFY_RPC_A_URL={primary}",
        f"VERIFY_RPC_B_URL={backup}",
        "",
        f"GRPC_ENDPOINT={v.get('GRPC_ENDPOINT', '')}",
        f"GRPC_TOKEN={v.get('GRPC_TOKEN', '')}",
        "GRPC_TLS=true",
        "GRPC_COMMITMENT=processed",
        "",
        f"JITO_URL={v.get('JITO_URL', JITO_TOKYO)}",
        "",
        "ALLOW_LIVE=false",
        "SNAPSHOT_MAX_AGE_MS=600",
        "HARD_MAX_SOL_PER_TX=5",
        "HARD_MAX_SOL_PER_ORDER=25",
        "HARD_MAX_TIP_SOL=0.05",
        "LOG_LEVEL=INFO",
        "",
    ]
    return "\n".join(lines)


def write_private(path: Path, text: str, owner: str | None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.replace(tmp, path)
    os.chmod(path, 0o600)
    if owner:
        pw = pwd.getpwnam(owner)
        os.chown(path, pw.pw_uid, pw.pw_gid)


def telegram(token: str, method: str, **params) -> dict:
    import httpx

    r = httpx.post(f"https://api.telegram.org/bot{token}/{method}", json=params, timeout=15)
    return r.json()


def detect_telegram_user(token: str) -> list[tuple[int, str]]:
    j = telegram(token, "getUpdates", timeout=0, allowed_updates=["message"])
    seen: dict[int, str] = {}
    for u in j.get("result") or []:
        frm = (u.get("message") or {}).get("from") or {}
        if frm.get("id") and not frm.get("is_bot"):
            seen[int(frm["id"])] = frm.get("username") or frm.get("first_name") or ""
    return list(seen.items())


def enable_credential_in_unit(unit: Path) -> bool:
    if not unit.exists():
        return False
    s = unit.read_text()
    new = s.replace("#LoadCredentialEncrypted=", "LoadCredentialEncrypted=")
    if new != s:
        unit.write_text(new)
    return True


def run_as(user: str | None, cmd: list[str], env_extra: dict[str, str], cwd: Path) -> int:
    env = {**os.environ, **env_extra}
    drop_privileges = None
    if user:
        pw = pwd.getpwnam(user)
        env.update({"HOME": pw.pw_dir, "USER": user, "LOGNAME": user})

        def _drop() -> None:  # run the child as the service user, not root
            os.setgid(pw.pw_gid)
            os.initgroups(user, pw.pw_gid)
            os.setuid(pw.pw_uid)

        drop_privileges = _drop
    return subprocess.run(cmd, cwd=cwd, env=env, preexec_fn=drop_privileges).returncode


# --------------------------------------------------------------------------------------- main --
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--app-dir", default=str(ROOT))
    ap.add_argument("--user", default="solbot")
    ap.add_argument("--no-systemd", action="store_true")
    a = ap.parse_args()
    app = Path(a.app_dir)
    user = a.user if a.user and _user_exists(a.user) else None
    if not a.no_systemd and os.geteuid() != 0:
        sys.exit("Chạy bằng sudo: sudo /opt/solbot/.venv/bin/python /opt/solbot/scripts/setup_wizard.py")
    env_path = app / ".env"
    cur = real_values(read_env(env_path))
    print("\n=== Cấu hình solbot (token/passphrase gõ ẩn, không hiển thị) ===\n")

    # 1. RPC
    print("1) RPC chính — dán URL Helius đầy đủ hoặc chỉ API key Helius")
    while True:
        try:
            primary = rpc_url_from(ask("   RPC chính", cur.get("VERIFY_RPC_A_URL") or None, secret=True))
            break
        except ValueError as e:
            print(f"   ✗ {e}")
    backup = ask("   RPC dự phòng (nhà cung cấp khác)", cur.get("VERIFY_RPC_B_URL") or PUBLICNODE_RPC)
    for name, url in (("chính", primary), ("dự phòng", backup)):
        ok, info = _rpc_ping(url)
        print(f"   {'✓' if ok else '✗'} RPC {name}: {info}")

    # 2. gRPC
    print("\n2) Yellowstone gRPC PublicNode (token cá nhân tại allnodes.com/publicnode; Enter để bỏ qua → HTTP polling)")
    grpc_token = getpass.getpass("   GRPC token" + (" [Enter = giữ nguyên]" if cur.get("GRPC_TOKEN") else "") + ": ").strip()
    grpc_token = grpc_token or cur.get("GRPC_TOKEN", "")
    grpc_endpoint = (cur.get("GRPC_ENDPOINT") or PUBLICNODE_GRPC) if grpc_token else ""

    # 3. Telegram
    print("\n3) Telegram — token bot lấy từ @BotFather")
    while True:
        tg_token = ask("   Bot token", cur.get("TELEGRAM_BOT_TOKEN") or None, secret=True)
        try:
            me = telegram(tg_token, "getMe")
        except Exception as e:
            print(f"   ✗ không gọi được Telegram: {type(e).__name__}")
            continue
        if me.get("ok"):
            bot_name = me["result"].get("username")
            print(f"   ✓ bot @{bot_name}")
            break
        print(f"   ✗ token sai: {me.get('description')}")
    allowed = cur.get("TELEGRAM_ALLOWED_USER_IDS", "")
    if not allowed or yes("   Xác định lại Telegram ID được phép điều khiển bot?", default=not allowed):
        input(f"   → Mở Telegram, gửi /start cho @{bot_name}, rồi nhấn Enter tại đây…")
        users = []
        for _ in range(5):
            users = detect_telegram_user(tg_token)
            if users:
                break
            time.sleep(2)
        if users:
            for uid, name in users:
                print(f"   tìm thấy: {uid} ({name})")
            allowed = ",".join(str(uid) for uid, _ in users) if len(users) == 1 else \
                ask("   Nhập ID được phép (phân cách dấu phẩy)", str(users[0][0]))
            if len(users) == 1 and not yes(f"   Dùng ID {allowed}?"):
                allowed = ask("   Nhập ID")
        else:
            allowed = ask("   Không thấy tin nhắn. Nhập ID thủ công (lấy từ @userinfobot)")

    # 4. Wallet
    print("\n4) Ví (keystore mã hóa)")
    from solders.keypair import Keypair

    from solbot.wallet import decrypt_keystore, encrypt_keypair

    ks_rel = "secrets/wallet.enc.json"
    ks = app / ks_rel
    passphrase = None
    if ks.exists() and yes(f"   Đã có ví {ks_rel}. Giữ ví này?"):
        doc = json.loads(ks.read_text())
        while True:
            pw_ = getpass.getpass("   Passphrase của ví hiện có: ")
            try:
                decrypt_keystore(doc, pw_)
                passphrase = pw_
                print(f"   ✓ ví {doc['pubkey']}")
                break
            except Exception:
                print("   ✗ sai passphrase")
    else:
        if yes("   Nhập ví có sẵn từ file keypair JSON (solana-keygen)?", default=False):
            src = Path(ask("   Đường dẫn file keypair JSON")).expanduser()
            kp = Keypair.from_bytes(bytes(json.loads(src.read_text())))
        else:
            kp = Keypair()
        while True:
            p1 = getpass.getpass("   Đặt passphrase (≥ 12 ký tự): ")
            p2 = getpass.getpass("   Nhập lại passphrase: ")
            if p1 != p2:
                print("   ✗ không khớp")
            elif len(p1) < 12:
                print("   ✗ quá ngắn")
            else:
                passphrase = p1
                break
        if ks.exists():
            backup_ks = ks.with_name(f"wallet.enc.{int(time.time())}.bak.json")
            shutil.copy2(ks, backup_ks)
            print(f"   (đã sao lưu ví cũ: {backup_ks.name})")
        write_private(ks, json.dumps(encrypt_keypair(kp, passphrase), indent=1), user)
        os.chmod(ks.parent, 0o700)
        print(f"   ✓ ví {kp.pubkey()}  →  {ks}")
        print("   ⚠ Sao lưu file ví + passphrase ở nơi an toàn. Mất cả hai = mất ví.")

    # 5. systemd credential for the passphrase
    if not a.no_systemd:
        cred = Path("/etc/solbot/wallet_pass.cred")
        cred.parent.mkdir(parents=True, exist_ok=True)
        r = subprocess.run(["systemd-creds", "encrypt", "--name=wallet_pass", "-", str(cred)],
                           input=passphrase.encode(), capture_output=True)
        if r.returncode == 0:
            os.chmod(cred, 0o600)
            enable_credential_in_unit(Path("/etc/systemd/system/solbot.service"))
            subprocess.run(["systemctl", "daemon-reload"], check=False)
            print(f"\n5) ✓ passphrase lưu dạng credential mã hóa: {cred}")
        else:
            print(f"\n5) ✗ systemd-creds lỗi: {r.stderr.decode()[:200]}")

    # 6. .env
    values = {"PRIMARY_RPC": primary, "BACKUP_RPC": backup, "WALLET_ENCRYPTED_PATH": ks_rel,
              "TELEGRAM_BOT_TOKEN": tg_token, "TELEGRAM_ALLOWED_USER_IDS": allowed,
              "GRPC_ENDPOINT": grpc_endpoint, "GRPC_TOKEN": grpc_token, "JITO_URL": cur.get("JITO_URL", JITO_TOKYO)}
    if env_path.exists():
        write_private(env_path.with_name(".env.bak"), env_path.read_text(), user)
    write_private(env_path, render_env(values), user)
    print(f"\n6) ✓ đã ghi {env_path} (600, ALLOW_LIVE=false)  RPC={mask(primary)} gRPC={'bật' if grpc_token else 'tắt'}"
          f" Telegram=@{bot_name} ID={allowed}")

    # 7. doctor
    print("\n7) Kiểm tra (doctor):\n")
    py = str(app / ".venv/bin/python") if (app / ".venv/bin/python").exists() else sys.executable
    rc = run_as(user, [py, "-m", "solbot", "doctor"], {"WALLET_PASSPHRASE": passphrase}, app)

    # 8. start
    if not a.no_systemd and yes("\n8) Khởi động bot (systemd, chế độ NO_SEND) ngay bây giờ?", default=rc == 0):
        subprocess.run(["systemctl", "enable", "--now", "solbot"], check=False)
        time.sleep(3)
        subprocess.run(["systemctl", "--no-pager", "--lines=8", "status", "solbot"], check=False)
        print(f"\n✓ Bot đang chạy. Mở Telegram, gửi /menu cho @{bot_name}. Log: journalctl -u solbot -f")
    else:
        print("\nKhởi động sau bằng: sudo systemctl enable --now solbot")


def _user_exists(u: str) -> bool:
    try:
        pwd.getpwnam(u)
        return True
    except KeyError:
        return False


def _rpc_ping(url: str) -> tuple[bool, str]:
    import httpx

    try:
        t0 = time.perf_counter()
        r = httpx.post(url, json={"jsonrpc": "2.0", "id": 1, "method": "getSlot"}, timeout=8)
        ms = (time.perf_counter() - t0) * 1000
        j = r.json()
        if "result" in j:
            return True, f"slot {j['result']}, {ms:.0f} ms"
        return False, str(j.get("error"))[:120]
    except Exception as e:
        return False, type(e).__name__


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nĐã hủy.")
        sys.exit(130)
